/**
 * tools/harness/report.ts — render the measurements as `build/BALANCE-REPORT.md`.
 *
 * build-doc §10.5: "Output: markdown report + suggested `balance.json` deltas."
 *
 * Everything printed here is computed from `HarnessMeasurements`. Nothing is a conclusion typed by
 * hand: a sentence that says a gym missed its band says so because the number missed the band, and
 * the report says which numbers it MEASURED and which claims it is INFERRING from them.
 *
 * Guardrail G12: no statement of effort in human engineering-hours appears in this file or in
 * anything it emits. The one duration reported is the wall-clock milliseconds the program itself
 * took, which is a property of the machine.
 */

