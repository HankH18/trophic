/**
 * tools/postprocess/atlas.ts — build-doc §9.3 step 4, "pack to sprite atlases".
 *
 * A shelf packer, not a maximal-rectangles packer. The inputs are a few hundred sprites at exactly
 * two or three sizes (96², 32×48, 32²), so shelves waste almost nothing, and the packer's real job
 * here is to be DETERMINISTIC: the frame table is written into the game's asset JSON, so a packer
 * whose output depends on input order silently invalidates every frame reference the next time the
 * batch is re-run. Entries are therefore sorted by id before packing, and the result is a pure
 * function of (ids, sizes, maxWidth).
 */
import type { Raster } from './raster.ts';
import { CHANNELS, assertWellFormed, blankRaster, idx } from './raster.ts';

export interface AtlasEntry {
  id: string;
  raster: Raster;
}

export interface AtlasFrame {
  x: number;
  y: number;
  w: number;
  h: number;
}

export interface Atlas {
  image: Raster;
  frames: Record<string, AtlasFrame>;
  /** Written beside the PNG so the game reads frames from data, never from a hard-coded grid. */
  meta: { maxWidth: number; padding: number; count: number };
}

export interface PackOptions {
  maxWidth: number;
  /** Transparent gutter between frames, so nearest-neighbour sampling cannot bleed a neighbour in. */
  padding: number;
}

export class AtlasError extends Error {}

export function packAtlas(entries: readonly AtlasEntry[], opts: PackOptions): Atlas {
  const { maxWidth, padding } = opts;
  if (maxWidth <= 0) throw new AtlasError(`packAtlas: maxWidth ${maxWidth}`);
  const sorted = [...entries].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  for (const e of sorted) assertWellFormed(e.raster, `packAtlas(${e.id})`);
  const seen = new Set<string>();
  for (const e of sorted) {
    if (seen.has(e.id)) throw new AtlasError(`packAtlas: duplicate id "${e.id}"`);
    seen.add(e.id);
    if (e.raster.width + padding * 2 > maxWidth) {
      throw new AtlasError(`packAtlas: "${e.id}" is ${e.raster.width}px wide, atlas is ${maxWidth}px`);
    }
  }

  const frames: Record<string, AtlasFrame> = {};
  let penX = padding;
  let penY = padding;
  let shelfHeight = 0;
  let usedWidth = 0;
  for (const e of sorted) {
    if (penX + e.raster.width + padding > maxWidth) {
      penX = padding;
      penY += shelfHeight + padding;
      shelfHeight = 0;
    }
    frames[e.id] = { x: penX, y: penY, w: e.raster.width, h: e.raster.height };
    penX += e.raster.width + padding;
    usedWidth = Math.max(usedWidth, penX);
    shelfHeight = Math.max(shelfHeight, e.raster.height);
  }
  const width = sorted.length === 0 ? 1 : usedWidth;
  const height = sorted.length === 0 ? 1 : penY + shelfHeight + padding;

  const image = blankRaster(width, height);
  for (const e of sorted) {
    const f = frames[e.id]!;
    for (let y = 0; y < f.h; y++) {
      const from = idx(e.raster, 0, y);
      image.data.set(e.raster.data.subarray(from, from + f.w * CHANNELS), idx(image, f.x, f.y + y));
    }
  }
  return { image, frames, meta: { maxWidth, padding, count: sorted.length } };
}

/** The JSON written beside the atlas PNG. Frames are emitted in sorted id order for stable diffs. */
export function atlasDescriptor(atlas: Atlas, imagePath: string): string {
  const frames: Record<string, AtlasFrame> = {};
  for (const id of Object.keys(atlas.frames).sort()) frames[id] = atlas.frames[id]!;
  return `${JSON.stringify(
    {
      _source: 'build-doc §9.3 step 4 — generated by tools/postprocess. Do not hand-edit.',
      image: imagePath,
      width: atlas.image.width,
      height: atlas.image.height,
      ...atlas.meta,
      frames,
    },
    null,
    2,
  )}\n`;
}
